"""Wind Risk Assessment Module.

Derives wind hazard severity from cyclone sustained wind speeds and Holland vortex radial wind fields.
Strict Zero-Fabrication: If wind speed is unavailable, returns available=False, risk_level="UNAVAILABLE".
"""

from typing import Any, Dict, Optional
from backend.app.impact.impact_models import ComponentRisk


class WindRiskAnalyzer:
    """Evaluates convective and cyclonic wind hazard based on physical wind fields."""

    @staticmethod
    def evaluate(
        wind_speed_knots: Optional[float],
        quadrant_radii: Optional[Dict[str, Any]] = None,
        is_perturbation: bool = False,
    ) -> ComponentRisk:
        if wind_speed_knots is None or wind_speed_knots <= 0:
            return ComponentRisk(
                available=False,
                risk_level="UNAVAILABLE",
                status="MISSING_WIND_DATA",
                source="Holland Vortex Baseline (Inactive)",
                source_type="UNAVAILABLE",
                method="None",
                explanation="Wind risk unavailable — maximum sustained wind and vortex data not provided.",
                metrics={},
                disclaimer="DO NOT INVENT WIND SPEED WHEN MEASUREMENTS ARE MISSING",
            )

        # Categorize hazard thresholds (Beaufort & IMD scale alignment)
        if wind_speed_knots >= 64.0:
            level = "EXTREME"
            desc = "Hurricane-force winds capable of structural devastation, widespread tree downing, and critical power grid destruction."
        elif wind_speed_knots >= 48.0:
            level = "HIGH"
            desc = "Storm-force winds capable of uprooting trees, damaging non-reinforced dwellings, and causing airborne projectile hazards."
        elif wind_speed_knots >= 34.0:
            level = "MODERATE"
            desc = "Gale-force winds causing damage to thatched roofs, small branches, and disrupting marine operations."
        else:
            level = "LOW"
            desc = "Sub-gale depression circulation with localized squally conditions."

        metrics: Dict[str, Any] = {
            "max_wind_speed_knots": round(wind_speed_knots, 1),
            "max_wind_speed_kmh": round(wind_speed_knots * 1.852, 1),
        }

        if quadrant_radii:
            r34_max = max((q.get("r34_km", 0.0) for q in quadrant_radii.values()), default=0.0)
            r50_max = max((q.get("r50_km", 0.0) for q in quadrant_radii.values()), default=0.0)
            r64_max = max((q.get("r64_km", 0.0) for q in quadrant_radii.values()), default=0.0)
            metrics["r34_max_km"] = round(r34_max, 1)
            metrics["r50_max_km"] = round(r50_max, 1)
            metrics["r64_max_km"] = round(r64_max, 1)

        source_type = "USER PERTURBATION" if is_perturbation else "MODEL-DERIVED"
        source_name = "User Scenario Wind Override" if is_perturbation else "Holland analytical vortex"

        return ComponentRisk(
            available=True,
            risk_level=level,
            status="ACTIVE_ESTIMATE",
            source=source_name,
            source_type=source_type,
            method="Holland (1980) Wind Field & Beaufort Gale Thresholds",
            explanation=f"Risk classification is derived from the analytical wind field generated by the Holland vortex baseline and is not an official warning. {desc}",
            metrics=metrics,
            disclaimer="MATHEMATICAL WIND HAZARD PROFILE — NOT AN OFFICIAL IMD WARNING ADVISORY",
        )


wind_risk_analyzer = WindRiskAnalyzer()

